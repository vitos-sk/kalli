// Описание одного слова команды с учётом предыдущего (для чисел и имён файлов)
export function describe(token: string, prev?: string): string | null {
  const t = token.replace(/^"|"$/g, '')
  if (EXACT[token]) return EXACT[token]
  if (EXACT[t] && /^[\w+/-]+$/.test(t)) return EXACT[t]
  const ph = token.match(/<(?:ip|target|domain|net|port)>/)
  if (ph && token === ph[0]) return PLACEHOLDER[ph[0]]
  if (/^https?:\/\//.test(token)) return `Адрес, к которому обращаемся. ${token.startsWith('https') ? 'https — защищённый канал.' : 'http — обычный канал без шифрования.'} Заглушки в нём подставятся сами.`
  if (/^\d+(,\d+)+$/.test(token)) return 'Список портов через запятую. Это «двери», которые проверяем.'
  if (/^\d+$/.test(token) && (prev === '-c' || prev === '-n')) return 'Сколько раз окликнуть.'
  if (/^\d+$/.test(token) && prev === '-p') return 'Номер порта, который проверяем.'
  if (/^\d+$/.test(token) && prev === '-p-') return null
  if (/\.(txt|xml)$/.test(token) && !token.includes('/')) return 'Имя файла. Сюда запишется результат — можно назвать по-своему.'
  if (/^\/[\w./-]+$/.test(token) && token !== '/dev/null') return 'Путь на сайте или API (что именно проверяем).'
  if (token.includes('%{http_code}')) return 'Формат вывода: напечатать только код ответа.'
  if (/^"==/.test(token)) return 'Напечатать, какой адрес проверяем сейчас.'
  if (/^_[\w-]+\._/.test(token)) return 'Что слушаем: все службы, которые устройства объявляют в сети.'
  if (/^\$\w+$/.test(token)) return 'Подставляется очередное значение из списка.'
  if (/^_dmarc\./.test(token)) return 'Особое имя для записи защиты почты (DMARC) рядом с твоим доменом.'
  if (/^[a-z0-9.-]+\.[a-z]{2,}$/i.test(token) && !/^</.test(token)) return 'Домен или адрес, который проверяем.'
  if (/^[a-z]+$/.test(token) && prev && /^(-p|-F|nmap)$/.test(prev) === false && token.length < 2) return null
  return null
}

export interface Part {
  token: string
  text: string
}

// Разбор команды по частям. Если у команды есть свои пояснения (flags) — они важнее общих.
export function breakdown(cmd: string, flags: CommandFlag[] = []): Part[] {
  const tokens = [...cmd.matchAll(/"[^"]*"|'[^']*'|\|{1,2}|;|&&|\S+/g)].map((m) => m[0])
  const parts: Part[] = []
  const seen = new Set<string>()
  tokens.forEach((token, i) => {
    const own = flags.find((f) => f.flag === token || f.flag.split(/\s+/)[0] === token)
    const text = own?.text ?? describe(token, tokens[i - 1])
    const key = token
    if (text && !seen.has(key)) {
      seen.add(key)
      parts.push({ token, text })
    }
  })
  // пояснения команды, которых нет среди слов (например, «/24» или «:<port>»)
  for (const f of flags) {
    if (!parts.some((p) => p.token === f.flag || f.flag.split(/\s+/)[0] === p.token)) parts.push({ token: f.flag, text: f.text })
  }
  return parts
}
